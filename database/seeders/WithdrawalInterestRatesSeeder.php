    private function addMonthlyRates(array &$rows,string $from,string $to,float $rate): void
    {
        $current=Carbon::parse($from)->endOfMonth();
        $end=Carbon::parse($to)->endOfMonth();

        while ($current->lte($end)) {
            $rows[]=$this->row(
                $current->format('Y-m-d'),
                $rate
            );

            $current=$current->copy()->addMonthNoOverflow()->endOfMonth();
        }
    }

    private function row(string $date,float $rate): array
    {
        return [
            'currency'=>'ZWG',
            'rate_date'=>$date,
            'rate_percentage'=>$rate,
            'source_authority'=>'Fundworx Withdrawal Interest Rates (ZWG) lookup supplied by LAPF',
            'notes'=>null,
            'is_active'=>true,
            'created_by'=>null,
            'updated_by'=>null,
        ];
    }
